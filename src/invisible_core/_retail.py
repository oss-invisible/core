"""The tables that a capture of retail Firefox decides.

Each file under ``data/retail/`` is generated by ``scripts/retail/gen_tables.py`` from
a dated capture under ``captures/`` (see ``docs/retail-captures.md`` and
``captures/pinned.json``) and is never edited by hand. This module only reads them;
it keeps nothing in memory between two calls (the core keeps no cache): every call reads
the file, and a module that needs a table at import reads it once into its own constant.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

_DIR = Path(__file__).parent / "data" / "retail"


def table(name: str) -> Any:
    """The parsed ``data/retail/<name>.json``."""
    return json.loads((_DIR / f"{name}.json").read_text(encoding="utf-8"))
